#!/usr/bin/env python3
"""Generate ../src/unicode_tables.h: exact CPython str.isalpha() ranges and
str.strip() whitespace set for THIS interpreter's Unicode database.

targeted.py semantics that depend on these:
  - pw.isalpha()           (Unicode categories behind _PyUnicode_IsAlpha)
  - l.strip()              (Py_UNICODE_ISSPACE set)
Regenerate whenever the reference CPython version changes.
"""
import os
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "unicode_tables.h")


def alpha_ranges():
    rs = []
    start = None
    for cp in range(0x110000):
        if chr(cp).isalpha():
            if start is None:
                start = cp
        elif start is not None:
            rs.append((start, cp - 1))
            start = None
    if start is not None:
        rs.append((start, 0x10FFFF))
    return rs


def strip_space_set():
    # exact str.strip() semantics: a lone char is stripped iff it is whitespace
    # per Py_UNICODE_ISSPACE (c.strip() removes it entirely)
    out = []
    for cp in range(0x110000):
        if chr(cp).strip() == "":
            out.append(cp)
    return out


def main():
    alpha = alpha_ranges()
    space = strip_space_set()

    # sanity: strip-set must equal str.isspace() set (both are Py_UNICODE_ISSPACE)
    isspace = {c for c in range(0x110000) if chr(c).isspace()}
    assert set(space) == isspace, "strip/isspace mismatch: %r" % (
        set(space) ^ isspace,)

    lines = []
    lines.append("/* GENERATED by tools/gen_utables.py -- do not edit.")
    lines.append(" * Source interpreter: %s" % sys.version.split()[0])
    lines.append(" * Unicode data: %s" % unicodedata.unidata_version)
    lines.append(" *")
    lines.append(" * sp_ucd_alpha[]: inclusive codepoint ranges where")
    lines.append(" * chr(cp).isalpha() is true (CPython str.isalpha).")
    lines.append(" * sp_ucd_space[]: codepoints stripped by str.strip().")
    lines.append(" */")
    lines.append("#ifndef UNICODE_TABLES_H")
    lines.append("#define UNICODE_TABLES_H")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append("typedef struct { uint32_t lo, hi; } sp_ucd_range;")
    lines.append("")
    lines.append("static const sp_ucd_range sp_ucd_alpha[] = {")
    for lo, hi in alpha:
        lines.append("  { 0x%04X, 0x%04X }," % (lo, hi))
    lines.append("};")
    lines.append("")
    lines.append("#define SP_UCD_ALPHA_NRANGES %du" % len(alpha))
    lines.append("")
    lines.append("static const uint32_t sp_ucd_space[] = {")
    for i in range(0, len(space), 12):
        lines.append("  " + " ".join("0x%02X," % c for c in space[i:i + 12]))
    lines.append("};")
    lines.append("")
    lines.append("#define SP_UCD_SPACE_N %du" % len(space))
    lines.append("")
    lines.append("#endif")
    lines.append("")

    with open(OUT, "w") as f:
        f.write("\n".join(lines))

    print("wrote %s: %d alpha ranges, %d space codepoints"
          % (OUT, len(alpha), len(space)))


if __name__ == "__main__":
    main()
